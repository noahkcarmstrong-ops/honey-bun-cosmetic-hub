const assert = require('node:assert/strict');
const {queryFor, priceFor, itemId} = require('./modern-catalog-sort.js');
const p = queryFor(new URLSearchParams('taxonomy=thukPQUFe5EHxRrtsgq43u&creatorName=roblox&SortType=5&salesTypeFilter=1&pxMin=0&IncludeNotForSale=true'), 'next/==');
const upper = queryFor(new URLSearchParams('CreatorName=Roblox&MinPrice=25&MaxPrice=50000&SortType=5'));
assert.equal(p.get('taxonomy'), 'thukPQUFe5EHxRrtsgq43u');
assert.equal(p.get('creatorName'), 'roblox');
assert.equal(p.get('sortType'), '5');
assert.equal(p.get('salesTypeFilter'), '1');
assert.equal(p.get('minPrice'), '0');
assert.equal(p.get('includeNotForSale'), 'true');
assert.equal(p.get('cursor'), 'next/==');
assert.equal(p.get('limit'), '30');
assert.equal(upper.get('creatorName'), 'Roblox');
assert.equal(upper.get('minPrice'), '25');
assert.equal(upper.get('maxPrice'), '50000');
assert.equal(priceFor({price:10, lowestResalePrice:618000000}), 'R$618,000,000');
assert.equal(itemId('https://www.roblox.com/catalog/73791866/Dark-Assassin'), 73791866);
console.log('Modern v2 high-low query, resale price and native item URL checks passed.');

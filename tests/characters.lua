-- Saved character snapshots: copy isolation, nil omission, deletion, and reload.
dofile('tests/storage.lua')
local makeCharacters = dofile('characters.lua')
local gui, storage = characterRejoin(909)
gui:SetAttribute('HoneyBunCosmeticSettings', 'settings-json')
gui:SetAttribute('HoneyBunCosmeticEmotes', 'emotes-json')
gui:SetAttribute('HoneyBunCosmeticAnimationBundle', 82)
local library = makeCharacters(gui)
local saved = library.save('  Outfit one  ', {records={{name='head'}}})
assert(saved.name == 'Outfit one' and saved.values.HoneyBunCosmeticClothes == nil, 'save trims name and omits nil attributes')
saved.values.HoneyBunCosmeticSettings = 'changed'
assert(library.get(saved.id).values.HoneyBunCosmeticSettings == 'settings-json', 'get returns an independent snapshot')
local listed = library.list(); listed[1].preview.records[1].name = 'changed'
assert(library.list()[1].preview.records[1].name == 'head', 'list returns an independent preview')
assert(library.delete(saved.id) and #library.list() == 0, 'delete removes the saved profile')
storage:destroy()
local rejoinedGui, rejoinedStorage = characterRejoin(909)
local rejoined = makeCharacters(rejoinedGui)
assert(#rejoined.list() == 0, 'deletion survives reload')
rejoinedStorage:destroy()

local malformedGui = characterRejoin(910)
malformedGui:SetAttribute('HoneyBunCosmeticCharacters', 'not-json')
local ok, message = pcall(function() makeCharacters(malformedGui) end)
assert(not ok and tostring(message):find('invalid JSON', 1, true), 'malformed character documents are rejected')
local http=game:GetService('HttpService')
local validGui,validStorage=characterRejoin(911)
local valid=makeCharacters(validGui)
validGui:SetAttribute('HoneyBunCosmeticSettings','first-look')
local first=valid.save('First')
validStorage:destroy()
local joinedGui,joinedStorage=characterRejoin(911)
local joined=makeCharacters(joinedGui)
assert(joined.get(first.id).values.HoneyBunCosmeticSettings=='first-look','Saved look survives leaving and rejoining')
joinedGui:SetAttribute('HoneyBunCosmeticSettings','second-look')
joined.delete(first.id)
local second=joined.save('Second')
assert(second.id>first.id and joined.get(second.id).values.HoneyBunCosmeticSettings=='second-look','IDs stay unique after deletion and reload')
local before=joinedGui:GetAttribute('HoneyBunCosmeticCharacters')
joinedGui:SetAttribute('HoneyBunCosmeticAnimationBundle','82')
assert(not pcall(joined.save,'Invalid') and joinedGui:GetAttribute('HoneyBunCosmeticCharacters')==before,'Invalid attribute type cannot overwrite library')
joinedGui:SetAttribute('HoneyBunCosmeticAnimationBundle',nil)
assert(not pcall(joined.save,'   ') and #joined.list()==1,'Blank names leave library unchanged')
for i=2,50 do joined.save('Look '..i) end
local fullDocument=joinedGui:GetAttribute('HoneyBunCosmeticCharacters')
assert(not pcall(joined.save,'Fifty-first') and #joined.list()==50 and joinedGui:GetAttribute('HoneyBunCosmeticCharacters')==fullDocument,'50-outfit limit rejects an extra save without changing existing characters')
local fullReload=makeCharacters(joinedGui)
assert(#fullReload.list()==50 and fullReload.get(second.id).values.HoneyBunCosmeticSettings=='second-look','All 50 outfits reload and existing outfit data stays intact')
joinedStorage:destroy()
local function reject(doc)
    local fixture=characterRejoin(912)
    fixture:SetAttribute('HoneyBunCosmeticCharacters',http:JSONEncode(doc))
    assert(not pcall(makeCharacters,fixture),'Reject invalid stored schema')
end
reject({version=2,nextId=1,profiles={}})
reject({version=1,nextId=math.huge,profiles={}})
reject({version=1,nextId=2,profiles={unexpected={}}})
reject({version=1,nextId=2,profiles={{id=1,name='Bad',values={HoneyBunCosmeticSettings=3}}}})
reject({version=1,nextId=2,profiles={{id=1,name='Bad',values={HoneyBunCosmeticAnimationBundle=-1}}}})
local editGui,editStorage=characterRejoin(913)
editGui:SetAttribute('HoneyBunCosmeticSettings','original-settings')
editGui:SetAttribute('HoneyBunCosmeticEmotes','original-emotes')
local edits=makeCharacters(editGui)
local original=edits.save('Original',{records={{name='old'}}})
local renamed=edits.rename(original.id,'  Renamed  ')
assert(renamed.id==original.id and renamed.name=='Renamed' and renamed.values.HoneyBunCosmeticSettings=='original-settings' and renamed.preview.records[1].name=='old','rename trims and preserves profile data')
local renamedDocument=editGui:GetAttribute('HoneyBunCosmeticCharacters')
assert(not pcall(edits.rename,original.id,'   ') and editGui:GetAttribute('HoneyBunCosmeticCharacters')==renamedDocument,'invalid rename is atomic')
editGui:SetAttribute('HoneyBunCosmeticSettings','updated-settings')
editGui:SetAttribute('HoneyBunCosmeticEmotes','updated-emotes')
local updated=edits.update(original.id,{records={{name='new'}}})
assert(updated.id==original.id and updated.name=='Renamed' and updated.values.HoneyBunCosmeticSettings=='updated-settings' and updated.values.HoneyBunCosmeticEmotes=='updated-emotes' and updated.preview.records[1].name=='new','update replaces values and preview while preserving id and name')
local updatedDocument=editGui:GetAttribute('HoneyBunCosmeticCharacters')
editGui:SetAttribute('HoneyBunCosmeticAnimationBundle',-1)
assert(not pcall(edits.update,original.id,nil) and editGui:GetAttribute('HoneyBunCosmeticCharacters')==updatedDocument,'invalid update is atomic')
editGui:SetAttribute('HoneyBunCosmeticAnimationBundle',nil)
local cleared=edits.update(original.id,nil)
assert(cleared.preview==nil and cleared.values.HoneyBunCosmeticSettings=='updated-settings','update allows clearing preview')
editStorage:destroy()
local reloadedEditGui,reloadedEditStorage=characterRejoin(913)
local reloadedEdits=makeCharacters(reloadedEditGui)
local reloadedProfile=reloadedEdits.get(original.id)
assert(reloadedProfile.name=='Renamed' and reloadedProfile.values.HoneyBunCosmeticSettings=='updated-settings' and reloadedProfile.preview==nil,'rename and update survive reload')
reloadedEditStorage:destroy()
print('Character save snapshot isolation, nil omission, deletion reload, and malformed input checks passed.')
